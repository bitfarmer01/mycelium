"""Request IDs + structured JSON logs (feature 1): one JSON log line per request,
carrying the same request_id the response returns (header + JSON body)."""
from __future__ import annotations

import json
import logging
import sys
import types

import httpx
import pytest

LOGGER = "mycelium.request"


def _stub(monkeypatch, name: str, **funcs) -> types.ModuleType:
    mod = types.ModuleType(name)
    for k, v in funcs.items():
        setattr(mod, k, v)
    monkeypatch.setitem(sys.modules, name, mod)
    return mod


@pytest.fixture
def client():
    from app.server import app

    return httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://test")


@pytest.fixture
def request_logs(caplog):
    caplog.set_level(logging.INFO, logger=LOGGER)
    return caplog


def _json_lines(caplog) -> list[dict]:
    out = []
    for rec in caplog.records:
        if rec.name != LOGGER:
            continue
        out.append(json.loads(rec.message))
    return out


async def test_ask_one_json_log_line_matches_response_request_id(monkeypatch, client, request_logs):
    async def ask(text, session_id):
        return {"question_id": "question:q1", "spoken": "Hi", "screen": "x"}

    _stub(monkeypatch, "core.reflex", ask=ask)
    async with client as c:
        r = await c.post("/ask", json={"text": "who owns billing?", "session_id": "s1"})

    assert r.status_code == 200
    body = r.json()
    lines = _json_lines(request_logs)
    assert len(lines) == 1, f"expected exactly one request log line, got {len(lines)}"
    rec = lines[0]
    assert rec["request_id"] == body["request_id"], "log line and response must carry the same request_id"
    assert rec["request_id"] == r.headers["x-request-id"]
    assert rec["method"] == "POST" and rec["path"] == "/ask" and rec["status"] == 200
    assert isinstance(rec["duration_ms"], (int, float))
    for key in ("ts", "level", "request_id", "method", "path", "status", "duration_ms"):
        assert key in rec


async def test_inbound_x_request_id_is_honored(client, request_logs):
    async with client as c:
        r = await c.get("/healthz", headers={"X-Request-ID": "trace-abc-123"})

    assert r.status_code == 200
    assert r.headers["x-request-id"] == "trace-abc-123"
    rec = _json_lines(request_logs)[0]
    assert rec["request_id"] == "trace-abc-123"
    assert rec["method"] == "GET" and rec["path"] == "/healthz"


async def test_ask_body_carries_request_id_other_routes_header_only(monkeypatch, client, request_logs):
    # /ask is the acceptance surface: its JSON body carries request_id.
    # Other routes keep their exact response bodies; the header is their carrier.
    async def ask(text, session_id):
        return {"question_id": "question:q1", "spoken": "Hi", "screen": "x"}

    _stub(monkeypatch, "core.reflex", ask=ask)
    async with client as c:
        health = await c.get("/healthz")
        ask_r = await c.post("/ask", json={"text": "q", "session_id": "s1"})
    assert health.json().get("request_id") is None
    assert health.headers["x-request-id"]
    assert ask_r.json()["request_id"] == ask_r.headers["x-request-id"]


async def test_handler_exception_still_logs_one_line(monkeypatch, request_logs):
    from app.server import app

    async def boom(text, session_id):
        raise RuntimeError("cli down")

    _stub(monkeypatch, "core.reflex", ask=boom)
    # raise_app_exceptions=False lets ServerErrorMiddleware turn the raise into a 500.
    transport = httpx.ASGITransport(app=app, raise_app_exceptions=False)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as c:
        r = await c.post("/ask", json={"text": "q", "session_id": "s1"})

    assert r.status_code == 500
    lines = _json_lines(request_logs)
    assert len(lines) == 1
    assert lines[0]["status"] == 500
    # The 500 here is generated by ServerErrorMiddleware *outside* the request
    # middleware, so only the log line carries the correlation id on this path.
    assert lines[0]["request_id"]


async def test_request_id_registered_for_shutdown_drain(client, monkeypatch):
    # The middleware must register the request task so the shutdown drain can await it.
    registered = []

    class FakePending:
        def add(self, task):
            registered.append(task)

    async def ask(text, session_id):
        return {"spoken": "Hi"}

    _stub(monkeypatch, "core.reflex", ask=ask)
    from app.server import app

    app.state.pending = FakePending()
    try:
        async with client as c:
            await c.post("/ask", json={"text": "q", "session_id": "s1"})
        assert len(registered) == 1
    finally:
        del app.state.pending
